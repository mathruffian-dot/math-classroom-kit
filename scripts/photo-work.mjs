/** 會考式評分（0–3 分），整題一個分數；照片有幾小題就看全部小題。 */
function rubric({ items, key, ref, notes }) {
  const many = items.length > 1;
  return {
    criteria: [
      {
        id: 'kai',
        label: '會考評分（0–3 分）',
        points: 3,
        levels: [
          { score: 3, description: `${many ? '每一小題都' : ''}過程完整、答案正確：${key}` },
          { score: 2, description: `方法正確、過程大致完整，但${many ? '有一小題' : ''}有一處計算小錯，或沒有化到最簡` },
          { score: 1, description: `只有部分正確的關鍵步驟${many ? '（例如只做對一小題）' : ''}，或過程有重大錯誤` },
          { score: 0, description: '空白、只寫答案沒有過程，或方法錯誤' },
        ],
      },
    ],
    reference: ref,
    graderNotes: `接受其他正確的做法。${notes}`,
  };
}

for (const [lessonId, acts] of Object.entries(PHOTO)) {
  const file = join(root, 'content/written', `${lessonId}.json`);
  const data = JSON.parse(await readFile(file, 'utf8'));
  // 不新增題目：拿掉先前加的會考式手寫題頁，保留錯誤分析題的會考規準
  delete data.slides;
  data.photo = Object.fromEntries(Object.entries(acts).map(([id, a]) => [id, { items: a.items, rubric: rubric(a) }]));
  await writeFile(file, `${JSON.stringify(data, null, 2)}\n`);
  console.log(`✓ ${lessonId}：拍照批改 ${Object.keys(acts).length} 題`);
}
