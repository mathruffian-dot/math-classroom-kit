/* 可操作頁的判定要有解：在滑桿範圍內窮舉（不靠課程 JSON 的判定式字串）。 */
{
  const sols = (f, ranges) => {
    const out = [];
    const rec = (i, cur) => {
      if (i === ranges.length) return f(...cur) && out.push(cur.join(','));
      for (let v = ranges[i][0]; v <= ranges[i][1]; v++) rec(i + 1, [...cur, v]);
    };
    rec(0, []);
    return out;
  };
  const L6 = [[1, 6], [2, 3], [3, 2], [6, 1]];
  const want = {
    'a-tiles': [sols((p, q) => p + q === 7 && p * q === 12, [[1, 5], [1, 5]]), ['3,4', '4,3']],
    'b-concrete': [sols((p, q) => p * q === -6 && p + q === -1, [[-6, 6], [-6, 6]]), ['-3,2', '2,-3']],
    'c-tiles': [sols((a, p, q) => a === 2 && a * q + p === 7 && p * q === 3, [[1, 3], [1, 5], [1, 5]]), ['2,1,3']],
    'c-play': [sols((k, p, q) => p * q === -2 && L6[k][1] * p + L6[k][0] * q === 1, [[0, 3], [-6, 6], [-6, 6]]), ['1,-1,2', '2,2,-1']],
  };
  for (const [id, [got, exp]] of Object.entries(want))
    if (got.sort().join(' ') !== exp.sort().join(' ')) throw new Error(`${id} 的操作解是 ${got.join(' ')}，預期 ${exp.join(' ')}`);
}

