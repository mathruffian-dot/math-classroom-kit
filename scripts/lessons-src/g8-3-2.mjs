const V = {
  ...V0,
  crossSteps(o) {
    const out = V0.crossSteps(o);
    shown.set(out, [`${o.a ?? 1}*x**2+(${o.b})*x+(${o.c})`, ...o.trials.filter((t) => !t.mask).map((t) => sq(t.m, t.p, t.n, t.q))]);
    return out;
  },
  crossPlay(o) {
    const out = V0.crossPlay(o);
    const [m, n] = o.lefts ? o.lefts[o.k ?? 0] : [1, 1];
    shown.set(out, [`${o.a ?? 1}*x**2+(${o.b})*x+(${o.c})`, sq(m, o.p ?? 1, n, o.q ?? 1)]);
    return out;
  },
  algebraTiles(o) {
    const out = V0.algebraTiles(o);
    shown.set(out, [sq(1, o.p ?? 1, 1, o.q ?? 1)]);
    return out;
  },
  algebraTilesAx(o) {
    const out = V0.algebraTilesAx(o);
    shown.set(out, [sq(o.a ?? 1, o.p ?? 1, 1, o.q ?? 1)]);
    return out;
  },
};
