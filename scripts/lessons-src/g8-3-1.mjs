/** 變號（具體操作）：p − q 和 q − p 在數線上對稱於 0，所以差一個負號、平方後相等。 */
function signFlip({ p = 5, q = 2 } = {}) {
  return {
    view: { xMin: -7, xMax: 7, yMin: -1.4, yMax: 2.6, aspect: 'equal' },
    params: [
      { id: 'p', label: '$p$', min: 0, max: 6, step: 1, value: p },
      { id: 'q', label: '$q$', min: 0, max: 6, step: 1, value: q },
    ],
    shapes: [
      ...V.numberLine(-6, 6, 1),
      { type: 'segment', points: [[0, 0.25], ['p-q', 0.25]], color: C.violet, width: 4 },
      { type: 'segment', points: [[0, -0.25], ['q-p', -0.25]], color: C.orange, width: 4 },
      { type: 'point', x: 'p-q', y: 0, color: C.violet },
      { type: 'point', x: 'q-p', y: 0, color: C.orange },
      { type: 'text', x: 'p-q', y: 0.85, text: '$p-q$', size: 16, color: '#5a3fd6' },
      { type: 'text', x: 'q-p', y: 1.5, text: '$q-p$', size: 16, color: '#b4541a' },
    ],
    readouts: [
      { label: '$p-q$', expr: 'p-q' },
      { label: '$q-p$', expr: 'q-p' },
      { label: '$(p-q)^2$', expr: '(p-q)^2' },
      { label: '$(q-p)^2$', expr: '(q-p)^2' },
    ],
    caption: '$q-p=-(p-q)$：長度一樣、方向相反；平方後負號不見，$(q-p)^2=(p-q)^2$',
  };
}

